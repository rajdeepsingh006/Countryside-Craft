const Joi = require('joi');

const createProductSchema = Joi.object({
  name: Joi.string().trim().min(2).max(200).required(),
  slug: Joi.string().trim().allow(''),
  tagline: Joi.string().trim().allow(''),
  description: Joi.string().trim().allow('').default(''),
  detailedStory: Joi.string().trim().allow(''),
  material: Joi.string().trim().allow(''),
  dimensions: Joi.string().trim().allow(''),
  handleLength: Joi.string().trim().allow(''),
  closureType: Joi.string().trim().allow(''),
  features: Joi.array().items(Joi.string().trim()).default([]),
  images: Joi.array().items(Joi.string().trim()).default([]),
  video: Joi.string().allow(''),
  videoThumbnail: Joi.string().allow(''),
  price: Joi.number().min(0).required(),
  originalPrice: Joi.number().min(0).allow(null, 0),
  discountPercent: Joi.number().min(0).max(100).default(0),
  stock: Joi.number().integer().min(0).default(0),
  category: Joi.string().required(),
  tags: Joi.array().items(Joi.string().trim()).default([]),
  isFeatured: Joi.boolean().default(false),
  isBestseller: Joi.boolean().default(false),
  isNewArrival: Joi.boolean().default(false),
  isActive: Joi.boolean().default(true),
});

const updateProductSchema = Joi.object({
  name: Joi.string().trim().min(2).max(200),
  slug: Joi.string().trim().allow(''),
  tagline: Joi.string().trim().allow(''),
  description: Joi.string().trim().allow(''),
  detailedStory: Joi.string().trim().allow(''),
  material: Joi.string().trim().allow(''),
  dimensions: Joi.string().trim().allow(''),
  handleLength: Joi.string().trim().allow(''),
  closureType: Joi.string().trim().allow(''),
  features: Joi.array().items(Joi.string().trim()),
  images: Joi.array().items(Joi.string().trim()),
  video: Joi.string().allow(''),
  videoThumbnail: Joi.string().allow(''),
  price: Joi.number().min(0),
  originalPrice: Joi.number().min(0).allow(null, 0),
  discountPercent: Joi.number().min(0).max(100),
  stock: Joi.number().integer().min(0),
  category: Joi.string(),
  tags: Joi.array().items(Joi.string().trim()),
  isFeatured: Joi.boolean(),
  isBestseller: Joi.boolean(),
  isNewArrival: Joi.boolean(),
  isActive: Joi.boolean(),
}).min(1);

module.exports = { createProductSchema, updateProductSchema };
